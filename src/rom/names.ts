export function className(c: number) {
  return CLASS_NAMES[c] ?? `职业${c}`;
}

export function charName(c: number) {
  return CHAR_NAMES[c] ?? `人物${c}`;
}

export function itemName(id: number) {
  return ITEM_NAMES[id] ?? `道具${id.toString(16)}`;
}
